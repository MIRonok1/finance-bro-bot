"""Тестовая инфраструктура — не часть рантайма бота.

Локальная машина разработки под рукой имеет только Python 3.9, а проект
таргетится на 3.12 (см. CLAUDE.md) и намеренно использует его синтаксис
(`X | None`, `datetime.UTC`). Шим ниже даёт тестам проходить локально на
3.9; на настоящем 3.12 (прод, CI) он не делает ничего, потому что там
`datetime.UTC` уже существует."""

import datetime as _datetime

if not hasattr(_datetime, "UTC"):
    _datetime.UTC = _datetime.timezone.utc  # noqa: UP017 — это и есть шим для 3.9
