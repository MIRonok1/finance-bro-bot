"""Общие фильтры для хендлеров.

`not_a_command` — общий предохранитель для всех хендлеров, которые слушают
свободный текст внутри FSM-состояния (ответ в устном счёте/квизе, ввод
тикера/количества в портфеле, редактирование вопроса в `/review`).

Без него любая команда (`/stats`, `/subscribe`, ...), отправленная пока
пользователь застрял в такой сессии, тихо проглатывается этим хендлером —
он просто не различает "текст ответа" и "текст команды", раз фильтрует
только по состоянию. Роутер этого хендлера регистрируется в `main.py`
раньше роутера нужной команды, поэтому до самой команды дело не доходит
(проверено вживую: `/stats` во время активной сессии устного счёта отвечал
«Не смог распознать число» вместо статистики).
"""

from __future__ import annotations

from aiogram.types import Message


def not_a_command(message: Message) -> bool:
    return not (message.text or "").startswith("/")
